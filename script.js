// ========================================
// TURKISH TEXT NORMALIZATION
// ========================================

function normalizeText(text) {
    return text
        .toLocaleLowerCase("tr-TR")
        .trim();
}


// ========================================
// SHOW CITIES
// ========================================

function showCities() {
    container.innerHTML = "";
    document.querySelector("h2").textContent = "İller";
    searchBox.value = "";

    Object.keys(data).forEach(function(il) {
        const city = document.createElement("div");
        city.className = "city";
        city.textContent = il;

        city.addEventListener("click", function() {
            if (il === "İstanbul") {
                showRegions(il);
            } else {
                showDistricts(il);
            }
        });

        container.appendChild(city);
    });
}


// ========================================
// SHOW REGIONS (İSTANBUL YAKALARI)
// ========================================

function showRegions(il) {
    container.innerHTML = "";
    document.querySelector("h2").textContent = il + " - Yakalar";
    searchBox.value = "";

    const backButton = document.createElement("button");
    backButton.textContent = "← Geri";
    backButton.addEventListener("click", showCities);
    container.appendChild(backButton);

    Object.keys(data[il]).forEach(function(yaka) {
        const region = document.createElement("div");
        region.className = "city";
        region.textContent = yaka;

        region.addEventListener("click", function() {
            showDistricts(il, yaka);
        });

        container.appendChild(region);
    });
}


// ========================================
// SHOW DISTRICTS
// ========================================

function showDistricts(il, yaka = null) {
    container.innerHTML = "";
    document.querySelector("h2").textContent = yaka ? (il + " → " + yaka) : (il + " - İlçeler");
    searchBox.value = "";

    // BACK BUTTON
    const backButton = document.createElement("button");
    backButton.textContent = "← Geri";

    backButton.addEventListener("click", function() {
        if (yaka) {
            showRegions(il);
        } else {
            showCities();
        }
    });

    container.appendChild(backButton);

    // DISTRICTS LIST SOURCE
    const targetDistricts = yaka ? data[il][yaka] : data[il];

    Object.keys(targetDistricts).forEach(function(ilce) {
        const district = document.createElement("div");
        district.className = "city";
        district.textContent = ilce;

        district.addEventListener("click", function() {
            showInstitutions(il, ilce, yaka);
        });

        container.appendChild(district);
    });
}


// ========================================
// SHOW INSTITUTIONS
// ========================================

function showInstitutions(il, ilce, yaka = null) {
    container.innerHTML = "";
    document.querySelector("h2").textContent = yaka ? (il + " → " + yaka + " → " + ilce) : (il + " → " + ilce);
    searchBox.value = "";

    // BACK BUTTON
    const backButton = document.createElement("button");
    backButton.textContent = "← Geri";

    backButton.addEventListener("click", function() {
        showDistricts(il, yaka);
    });

    container.appendChild(backButton);

    // INSTITUTIONS DATA SOURCE
    const list = yaka ? data[il][yaka][ilce] : data[il][ilce];

    list.forEach(function(institution) {
        const item = document.createElement("div");
        item.className = "city";
        item.textContent = institution;

        container.appendChild(item);
    });
}


// ========================================
// SEARCH
// ========================================

function searchAll() {
    const searchText = normalizeText(searchBox.value);

    if (searchText === "") {
        showCities();
        return;
    }

    container.innerHTML = "";
    document.querySelector("h2").textContent = "Arama Sonuçları";

    let resultFound = false;
    const searchWords = searchText.split(" ").filter(w => w.length > 0);

    // RECURSIVE SEARCH HELPER
    function searchRecursive(obj, currentPath = []) {
        Object.keys(obj).forEach(key => {
            const val = obj[key];
            if (Array.isArray(val)) {
                // val is institution array, key is district
                val.forEach(inst => {
                    const fullText = [...currentPath, key, inst].join(" ");
                    const normalizedFullText = normalizeText(fullText);

                    const isMatch = searchWords.every(word => normalizedFullText.includes(word));
                    if (isMatch) {
                        resultFound = true;
                        const result = document.createElement("div");
                        result.className = "city";
                        result.textContent = [...currentPath, key, inst].join(" → ");

                        result.addEventListener("click", function() {
                            const il = currentPath[0];
                            if (il === "İstanbul") {
                                const yaka = currentPath[1];
                                showInstitutions(il, key, yaka);
                            } else {
                                showInstitutions(il, key);
                            }
                        });

                        container.appendChild(result);
                    }
                });
            } else if (typeof val === "object") {
                searchRecursive(val, [...currentPath, key]);
            }
        });
    }

    searchRecursive(data);

    if (!resultFound) {
        const noResult = document.createElement("div");
        noResult.className = "city";
        noResult.textContent = "Sonuç bulunamadı.";
        container.appendChild(noResult);
    }
}


